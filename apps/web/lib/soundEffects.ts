/** Crystal glass harmonic chime on job completion */
export function playCrystalChime() {
  const ctx = getAudioContext();
  if (!ctx) return;

  const freqs = [1046.5, 1318.5, 1567.98]; // C6, E6, G6 glass chord

  freqs.forEach((freq, idx) => {
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = 'sine';
    osc.frequency.setValueAtTime(freq, ctx.currentTime + idx * 0.05);

    gain.gain.setValueAtTime(0.03, ctx.currentTime + idx * 0.05);
    gain.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + idx * 0.05 + 0.6);

    osc.connect(gain);
    gain.connect(ctx.destination);

    osc.start(ctx.currentTime + idx * 0.05);
    osc.stop(ctx.currentTime + idx * 0.05 + 0.6);
  });
}

